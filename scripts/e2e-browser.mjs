// End-to-end check with real components (developer machine; Linux + Chromium via Playwright):
//   WAN Identity Hub (patched, dev mode)  ←OIDC→  backend  ←HTTP→  native host  ←stdio→  extension in Chromium
// Prerequisites: hub running at $HUB (default http://localhost:4100) with the desktop-client patch and the
// demo account; `mvn -f backend/pom.xml package dependency:build-classpath -Dmdep.outputFile=/var/tmp/wdm-cp.txt`;
// same for native-messaging/host (→ /var/tmp/wdm-host-cp.txt); `npm --prefix browser-extensions run build`; ffmpeg.
// Run: xvfb-run -a node scripts/e2e-browser.mjs
import { createRequire } from "node:module";
import { spawn, execFileSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync, chmodSync, existsSync, readdirSync } from "node:fs";
import { createServer } from "node:http";
import { tmpdir } from "node:os";
const { chromium } = createRequire(import.meta.url)("playwright"); // global install in CI images, or `npm i -g playwright`
import { join, resolve } from "node:path";

const ROOT = resolve(new URL("..", import.meta.url).pathname);
const HUB = process.env.HUB ?? "http://localhost:4100";
const PSQL = process.env.WAN_HUB_PSQL ?? "postgresql://postgres:postgres@localhost:5432/wan_identity";
const work = mkdtempSync(join(tmpdir(), "wdm-e2e-"));
const dataDir = join(work, "data"), downloads = join(work, "downloads"), profile = join(work, "chrome");
[dataDir, downloads, profile].forEach((d) => mkdirSync(d, { recursive: true }));
const step = (m) => console.log(`\n▶ ${m}`);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const procs = [];

async function until(what, fn, ms = 30000) {
  const end = Date.now() + ms;
  for (;;) {
    const v = await fn().catch(() => undefined);
    if (v) return v;
    if (Date.now() > end) throw new Error("Timed out waiting for " + what);
    await sleep(250);
  }
}

try {
  step("Fixture page with a real video (generated by FFmpeg: test pattern, no third-party content)");
  const site = join(work, "site");
  mkdirSync(site);
  execFileSync("ffmpeg", ["-v", "error", "-f", "lavfi", "-i", "testsrc=duration=3:size=640x360:rate=25", "-c:v", "libx264",
    "-pix_fmt", "yuv420p", join(site, "clip.mp4")]);
  writeFileSync(join(site, "index.html"), `<!doctype html><title>WAN test page</title><h1>Video</h1>
    <video src="clip.mp4" controls muted preload="metadata" width="640"></video>`);
  const pageServer = createServer((req, res) => {
    const f = join(site, req.url === "/" ? "index.html" : req.url.slice(1));
    if (!existsSync(f)) return res.writeHead(404).end();
    const body = readFileSync(f);
    const type = f.endsWith(".mp4") ? "video/mp4" : "text/html";
    const range = req.headers.range?.match(/bytes=(\d+)-(\d*)/);
    if (range) {
      const start = +range[1], end = range[2] ? +range[2] : body.length - 1;
      res.writeHead(206, { "Content-Type": type, "Accept-Ranges": "bytes", "Content-Range": `bytes ${start}-${end}/${body.length}`, "Content-Length": end - start + 1 });
      return res.end(body.subarray(start, end + 1));
    }
    res.writeHead(200, { "Content-Type": type, "Accept-Ranges": "bytes", "Content-Length": body.length }).end(body);
  }).listen(0, "127.0.0.1");
  await new Promise((r) => pageServer.once("listening", r));
  const pageUrl = `http://127.0.0.1:${pageServer.address().port}/`;

  step("Backend (embedded API) configured for the hub");
  const cp = [join(ROOT, "backend/target/classes"), readFileSync("/var/tmp/wdm-cp.txt", "utf8").trim()].join(":");
  const backend = spawn("java", ["-cp", cp, "com.wan.downloadmanager.WanDownloadManagerBackend",
    `--wan.data-dir=${dataDir}`, "--wan.security.allow-loopback-downloads=true",
    `--wan.identity.issuer=${HUB}/oidc`, "--wan.identity.client-id=wan-download-manager"], { stdio: ["ignore", "ignore", "inherit"] });
  procs.push(backend);
  const runtime = await until("backend runtime.json", async () => existsSync(join(dataDir, "runtime.json")) && JSON.parse(readFileSync(join(dataDir, "runtime.json"))));
  const api = async (method, path, body) => {
    const r = await fetch(`http://127.0.0.1:${runtime.port}${path}`, { method, headers: { Authorization: `Bearer ${runtime.token}`, "Content-Type": "application/json" }, body: body && JSON.stringify(body) });
    const text = await r.text();
    return { status: r.status, body: text ? JSON.parse(text) : null };
  };
  const settings = (await api("GET", "/api/v1/settings")).body;
  await api("PUT", "/api/v1/settings", { ...settings, downloadDir: downloads, mediaOutputDir: downloads });
  console.log("  API on port", runtime.port);

  step("Hub: the platform owner has given the demo account the Pro tier");
  execFileSync("psql", [PSQL, "-qc", "insert into entitlements (user_id, platform_id, status, roles, granted_at) select id, 'wan-download-manager', 'active', '{pro}', now() from users where email = 'demo@wan.dev' on conflict (user_id, platform_id) do update set status = 'active', roles = '{pro}'"]);

  step("Chromium with the unpacked extension and the native host registered");
  const ext = join(work, "ext");
  cpSync(join(ROOT, "browser-extensions/dist/chrome"), ext, { recursive: true });
  const manifest = JSON.parse(readFileSync(join(ext, "manifest.json")));
  // Test build only: pre-grant the fixture origin (a user grants this in the popup; prompts cannot be clicked headlessly).
  manifest.host_permissions = ["http://127.0.0.1/*"];
  manifest.content_scripts = [{ matches: ["http://127.0.0.1/*"], js: ["content.js"], run_at: "document_idle" }];
  writeFileSync(join(ext, "manifest.json"), JSON.stringify(manifest, null, 2));
  const wrapper = join(work, "wdm-native-host.sh");
  const hostCp = [join(ROOT, "native-messaging/host/target/wdm-native-host-0.1.0-SNAPSHOT.jar"), readFileSync("/var/tmp/wdm-host-cp.txt", "utf8").trim()].join(":");
  writeFileSync(wrapper, `#!/bin/sh\nunset JAVA_TOOL_OPTIONS\nWAN_DATA_DIR='${dataDir}' exec java -cp '${hostCp}' com.wan.downloadmanager.nativehost.NativeHost "$@"\n`);
  chmodSync(wrapper, 0o755);
  const context = await chromium.launchPersistentContext(profile, {
    headless: false,
    args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`, "--autoplay-policy=no-user-gesture-required"],
  });
  const sw = context.serviceWorkers()[0] ?? (await context.waitForEvent("serviceworker"));
  const extId = new URL(sw.url()).host;
  writeFileSync(join(dataDir, "allowed-origins.properties"), `chrome=${extId}\n`);
  mkdirSync(join(profile, "NativeMessagingHosts"), { recursive: true });
  writeFileSync(join(profile, "NativeMessagingHosts", "com.wan.download_manager.json"), JSON.stringify({
    name: "com.wan.download_manager", description: "WAN Download Manager", path: wrapper, type: "stdio",
    allowed_origins: [`chrome-extension://${extId}/`],
  }));
  console.log("  extension id", extId);

  step("Sign in through WAN Identity Hub (system browser = this Chromium)");
  const login = await api("POST", "/api/v1/account/login");
  if (login.status !== 200) throw new Error("login start failed: " + JSON.stringify(login.body));
  const hubPage = await context.newPage();
  await hubPage.goto(`${HUB}/health`);
  const csrf = (await context.cookies(HUB)).find((c) => c.name === "csrf_token")?.value
    ?? (await hubPage.request.get(`${HUB}/api/auth/session`), (await context.cookies(HUB)).find((c) => c.name === "csrf_token").value);
  const hubLogin = await hubPage.request.post(`${HUB}/api/auth/login`, { headers: { "X-CSRF-Token": csrf },
    data: { method: "email", identifier: "demo@wan.dev", password: "Demo@1234", remember: false } });
  if (!hubLogin.ok()) throw new Error("hub login failed " + (await hubLogin.text()));
  await hubPage.goto(login.body.authorizationUrl);
  await hubPage.waitForURL(/127\.0\.0\.1:\d+\/callback/);
  console.log("  loopback page:", await hubPage.locator("h1").textContent());
  const account = await until("signed in", async () => { const a = (await api("GET", "/api/v1/account")).body; return a.status === "SIGNED_IN" && a; });
  console.log(`  signed in as ${account.profile.email}, tier ${account.entitlement.tier} (${account.entitlement.source})`);
  if (account.entitlement.tier !== "PRO") throw new Error("expected PRO from the hub entitlement");

  step("Open the page: content script detects the video, background asks the app via the native host");
  const page = await context.newPage();
  await page.goto(pageUrl);
  const tabId = await until("badge", async () => {
    const id = await sw.evaluate(async (u) => (await chrome.tabs.query({ url: u + "*" }))[0]?.id, pageUrl);
    const text = id && (await sw.evaluate((t) => chrome.action.getBadgeText({ tabId: t }), id));
    return text === "1" && id;
  });
  console.log("  toolbar badge shows 1 detected video on tab", tabId);
  const browsers = (await api("GET", "/api/v1/browser/status")).body;
  console.log("  app sees:", browsers.map((b) => `${b.browser}=${b.connected ? "connected" : "-"}`).join(" "));

  step("Video Grabber popup → verified formats → download");
  const popup = await context.newPage();
  await popup.goto(`chrome-extension://${extId}/popup.html?tab=${tabId}`);
  await popup.getByText("Connected to WAN Download Manager").waitFor();
  if (process.env.E2E_DEBUG) {
    const probe = await popup.evaluate(async ([t, u]) => chrome.runtime.sendMessage({ kind: "verify", tabId: t, url: u }), [tabId, pageUrl + "clip.mp4"]);
    console.log("  DEBUG verify reply:", JSON.stringify(probe).slice(0, 600));
  }
  await popup.getByRole("button", { name: "Get formats" }).click();
  const fmt = popup.locator(".format").first();
  await fmt.waitFor({ timeout: 20000 }).catch(async (e) => {
    throw new Error("No format listed. Popup shows: " + (await popup.locator("#list").innerText()));
  });
  console.log("  format offered:", (await fmt.locator("span").textContent()).trim());
  await popup.screenshot({ path: join(ROOT, "docs/screenshots/extension-popup.png") }).catch(() => undefined);
  await fmt.getByRole("button", { name: "Download" }).click();
  await popup.getByRole("button", { name: "Added ✓" }).waitFor();
  const done = await until("download complete", async () => {
    const list = (await api("GET", "/api/v1/downloads?filter=completed")).body;
    return list.find((d) => d.source === "MEDIA");
  });
  const probe = JSON.parse(execFileSync("ffprobe", ["-v", "error", "-print_format", "json", "-show_streams", done.filePath]));
  console.log(`  downloaded ${done.fileName} (${done.totalBytes} bytes) → ${probe.streams[0].width}x${probe.streams[0].height}`);
  const original = readFileSync(join(site, "clip.mp4"));
  if (!readFileSync(done.filePath).equals(original)) throw new Error("downloaded file differs from the source");
  console.log("  byte-identical to the served file ✓");

  step("Context-menu style hand-off of a plain link (native host 'download' message)");
  const handoff = await sw.evaluate(async (u) => chrome.runtime.sendNativeMessage("com.wan.download_manager", { type: "download", id: "x", v: 1, url: u + "clip.mp4", pageUrl: u }), pageUrl);
  console.log("  host answered:", handoff.error ? handoff.error.code : handoff.result.status);

  step("Sign out (revokes the refresh token at the hub)");
  const out = (await api("POST", "/api/v1/account/logout")).body;
  console.log(`  revoked: ${out.revoked}, end-session URL offered: ${!!out.endSessionUrl}`); // never print tokens
  await context.close();
  pageServer.close();
  console.log("\nE2E PASSED");
} catch (e) {
  console.error("\nE2E FAILED:", e);
  process.exitCode = 1;
} finally {
  procs.forEach((p) => p.kill());
  execFileSync("psql", [PSQL, "-qc", "update entitlements set roles = '{free}' where platform_id = 'wan-download-manager'"]);
}
