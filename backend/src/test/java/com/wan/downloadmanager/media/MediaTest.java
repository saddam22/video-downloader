/**
 * Media detection, HLS download and conversion with fixtures generated by FFmpeg itself
 * (test pattern + sine tone: no third-party content, no network). Skipped without FFmpeg.
 */
@EnabledIf("ffmpegAvailable")
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class MediaTest extends BackendTestBase {
    static boolean ffmpegAvailable() {
        try {
            return new ProcessBuilder("ffmpeg", "-version").start().waitFor() == 0;
        } catch (Exception e) {
            return false;
        }
    }

    @Autowired MediaService media;
    @Autowired DownloadService downloads;
    @Autowired ConversionService conversions;
    @Autowired ConversionJobRepository jobs;
    @Autowired FfmpegService ffmpeg;
    @Autowired EntitlementService entitlements;
    MockHttpServer server;
    Path fixtures;

    @BeforeAll
    void fixtures() throws Exception {
        fixtures = Files.createTempDirectory("wdm-media");
        run("ffmpeg", "-v", "error", "-f", "lavfi", "-i", "testsrc=duration=4:size=320x240:rate=25", "-f", "lavfi", "-i",
                "sine=frequency=440:duration=4", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest",
                "-f", "hls", "-hls_time", "1", "-hls_playlist_type", "vod", "-hls_segment_filename",
                fixtures.resolve("seg%03d.ts").toString(), fixtures.resolve("v240.m3u8").toString());
        run("ffmpeg", "-v", "error", "-f", "lavfi", "-i", "testsrc=duration=3:size=320x240:rate=25", "-f", "lavfi", "-i",
                "sine=frequency=440:duration=3", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest",
                fixtures.resolve("clip.mp4").toString());
        server = new MockHttpServer();
        try (Stream<Path> files = Files.list(fixtures)) {
            for (Path f : files.toList()) {
                var r = server.put("/media/" + f.getFileName(), Files.readAllBytes(f));
                if (f.toString().endsWith(".m3u8")) r.contentType = "application/vnd.apple.mpegurl";
                if (f.toString().endsWith(".mp4")) r.contentType = "video/mp4";
            }
        }
        server.put("/media/master.m3u8", ("#EXTM3U\n#EXT-X-STREAM-INF:BANDWIDTH=400000,RESOLUTION=320x240,CODECS=\"avc1.64000d,mp4a.40.2\"\nv240.m3u8\n").getBytes())
                .contentType = "application/vnd.apple.mpegurl";
        server.put("/media/enc.m3u8", ("#EXTM3U\n#EXT-X-TARGETDURATION:1\n#EXT-X-KEY:METHOD=AES-128,URI=\"key.bin\"\n#EXTINF:1,\nseg000.ts\n#EXT-X-ENDLIST\n").getBytes());
        server.put("/media/drm.mpd", ("<?xml version=\"1.0\"?><MPD xmlns=\"urn:mpeg:dash:schema:mpd:2011\" mediaPresentationDuration=\"PT4S\"><Period><AdaptationSet mimeType=\"video/mp4\">"
                + "<ContentProtection schemeIdUri=\"urn:uuid:edef8ba9-79d6-4ace-a3c8-27dcd51d21ed\"/><Representation id=\"1\" bandwidth=\"1\" width=\"320\" height=\"240\"><BaseURL>clip.mp4</BaseURL></Representation></AdaptationSet></Period></MPD>").getBytes());
    }

    @AfterAll
    void stop() {
        server.close();
    }

    @BeforeEach
    void pro() {
        entitlements.apply(new EntitlementService.State(EntitlementService.Tier.PRO, EntitlementService.Source.ONLINE, "active", List.of("pro"), 0L, null));
        media.clear();
    }

    @AfterEach
    void free() {
        entitlements.apply(EntitlementService.State.free(EntitlementService.Source.SIGNED_OUT));
    }

    static void run(String... cmd) throws Exception {
        Process p = new ProcessBuilder(cmd).inheritIO().start();
        assertThat(p.waitFor()).isZero();
    }

    MediaService.Report report(String path, Integer w, Integer h) {
        return new MediaService.Report("https://video.example/watch?v=1", "Test pattern", "CHROME",
                List.of(new MediaService.SourceReport(server.url(path), null, w, h, null, null)));
    }

    @Test
    void detectionNeedsTheVideoFeature() {
        entitlements.apply(EntitlementService.State.free(EntitlementService.Source.SIGNED_OUT));
        assertThatThrownBy(() -> media.detect(report("/media/master.m3u8", null, null))).isInstanceOf(WdmException.class)
                .hasMessageContaining("video.detection");
    }

    @Test
    void hlsMasterListsOnlyItsRealVariantsAndDownloadsToMp4() throws Exception {
        var sources = media.detect(report("/media/master.m3u8", null, null));
        assertThat(sources).hasSize(1);
        var src = sources.getFirst();
        assertThat(src.kind()).isEqualTo("HLS");
        assertThat(src.formats()).hasSize(1);
        assertThat(src.formats().getFirst().height()).isEqualTo(240);
        assertThat(src.formats().getFirst().label()).startsWith("240p");
        assertThat(media.detect(report("/media/master.m3u8", null, null)).getFirst().id()).as("duplicate filtered").isEqualTo(src.id());

        var d = media.download(src.id(), src.formats().getFirst().id());
        String status;
        long deadline = System.currentTimeMillis() + 30_000;
        do {
            Thread.sleep(100);
            status = downloads.find(d.id()).status();
        } while (!status.equals("COMPLETED") && !status.equals("FAILED") && System.currentTimeMillis() < deadline);
        var done = downloads.find(d.id());
        assertThat(status).as(String.valueOf(done.errorMessage())).isEqualTo("COMPLETED");
        assertThat(done.fileName()).isEqualTo("Test pattern 240p.mp4");
        var info = ffmpeg.probe(Path.of(done.filePath()));
        assertThat(info.durationSec()).isBetween(3.5, 4.5);
        assertThat(info.height()).isEqualTo(240);
        assertThat(info.audioCodec()).isEqualTo("aac");
    }

    @Test
    void plainFileUsesBrowserReportedDimensionsAndRealSize() {
        var src = media.detect(report("/media/clip.mp4", 320, 240)).getFirst();
        assertThat(src.kind()).isEqualTo("FILE");
        assertThat(src.formats()).singleElement().satisfies(f -> {
            assertThat(f.estimatedBytes()).isPositive();
            assertThat(f.label()).startsWith("240p · MP4 · ");
        });
    }

    @Test
    void encryptedAndDrmStreamsAreNeverOffered() {
        var enc = media.detect(report("/media/enc.m3u8", null, null)).getFirst();
        assertThat(enc.protectedContent()).isTrue();
        assertThat(enc.formats()).isEmpty();
        var drm = media.detect(report("/media/drm.mpd", null, null)).getFirst();
        assertThat(drm.protectedContent()).isTrue();
        assertThat(drm.formats()).isEmpty();
    }

    @Test
    void blobUrlsAreIgnored() {
        var r = new MediaService.Report("https://video.example/x", "t", "EDGE",
                List.of(new MediaService.SourceReport("blob:https://video.example/1234", "video/mp4", 1920, 1080, 10.0, null)));
        assertThat(media.detect(r)).isEmpty();
    }

    @Test
    void conversionToMp3IsValidatedAndInvalidInputFails() throws Exception {
        ConversionJob j = conversions.submit(fixtures.resolve("clip.mp4").toString(), "mp3", fixtures.resolve("out").toString());
        ConversionJob done = waitJob(j.getId());
        assertThat(done.getStatus()).as(String.valueOf(done.getErrorMessage())).isEqualTo(JobStatus.COMPLETED);
        var info = ffmpeg.probe(Path.of(done.getOutputPath()));
        assertThat(info.audioCodec()).isEqualTo("mp3");
        assertThat(info.videoCodec()).isNull();

        Path junk = fixtures.resolve("junk.mp4");
        Files.writeString(junk, "not a video");
        assertThat(waitJob(conversions.submit(junk.toString(), "mp3", null).getId()).getStatus()).isEqualTo(JobStatus.FAILED);
        assertThatThrownBy(() -> conversions.submit(fixtures.resolve("missing.mp4").toString(), "mp3", null)).isInstanceOf(WdmException.class);
    }

    @Test
    void conversionCanBeCancelled() throws Exception {
        Path longClip = fixtures.resolve("long.mp4");
        run("ffmpeg", "-v", "error", "-f", "lavfi", "-i", "testsrc=duration=120:size=1280x720:rate=30", "-c:v", "libx264", "-preset", "ultrafast", longClip.toString());
        ConversionJob j = conversions.submit(longClip.toString(), "webm", fixtures.resolve("out").toString());
        long deadline = System.currentTimeMillis() + 20_000;
        while (jobs.findById(j.getId()).orElseThrow().getStatus() != JobStatus.RUNNING && System.currentTimeMillis() < deadline) Thread.sleep(50);
        conversions.cancel(j.getId());
        assertThat(waitJob(j.getId()).getStatus()).isEqualTo(JobStatus.CANCELLED);
        assertThat(Path.of(j.getOutputPath())).doesNotExist();
    }

    ConversionJob waitJob(String id) throws InterruptedException {
        long deadline = System.currentTimeMillis() + 60_000;
        ConversionJob j;
        do {
            Thread.sleep(100);
            j = jobs.findById(id).orElseThrow();
        } while ((j.getStatus() == JobStatus.QUEUED || j.getStatus() == JobStatus.RUNNING) && System.currentTimeMillis() < deadline);
        return j;
    }

    @Test
    void manifestParsing() throws Exception {
        var master = ManifestParser.parseHlsMaster("""
                #EXTM3U
                #EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID="aud",NAME="English",LANGUAGE="en",URI="audio/en.m3u8"
                #EXT-X-STREAM-INF:BANDWIDTH=5000000,RESOLUTION=1920x1080,CODECS="avc1.640028,mp4a.40.2",AUDIO="aud"
                1080/index.m3u8
                #EXT-X-STREAM-INF:BANDWIDTH=800000,RESOLUTION=640x360
                360/index.m3u8
                """, URI.create("https://cdn.example/v/master.m3u8"));
        assertThat(master.variants()).extracting(ManifestParser.Variant::height).containsExactly(1080, 360);
        assertThat(master.variants().getFirst().uri().toString()).isEqualTo("https://cdn.example/v/1080/index.m3u8");
        assertThat(master.audio().getFirst().uri().toString()).isEqualTo("https://cdn.example/v/audio/en.m3u8");
        assertThat(ManifestParser.parseHlsMaster("#EXTM3U\n#EXT-X-SESSION-KEY:METHOD=SAMPLE-AES,KEYFORMAT=\"com.widevine\"\n", URI.create("https://x/")).protectedContent()).isTrue();
        assertThatThrownBy(() -> ManifestParser.parseDash("<!DOCTYPE x [<!ENTITY e SYSTEM \"file:///etc/passwd\">]><MPD>&e;</MPD>", URI.create("https://x/")))
                .as("XXE refused").isInstanceOf(Exception.class);
        assertThat(ManifestParser.parseIsoDuration("PT1H2M3.5S")).isEqualTo(3723.5);
    }
}
